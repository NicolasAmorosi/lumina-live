const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getDisplays: () => ipcRenderer.invoke('get-displays'),
  openPresentation: (id) => ipcRenderer.invoke('open-presentation', id),
  closePresentation: () => ipcRenderer.invoke('close-presentation'),
  showContent: (c) => ipcRenderer.invoke('show-content', c),
  showBlack: () => ipcRenderer.invoke('show-black'),
  showLogo: () => ipcRenderer.invoke('show-logo'),
  videoCommand: (cmd) => ipcRenderer.invoke('video-command', cmd),
  presentationShow: () => ipcRenderer.invoke('presentation-show'),
  presentationHide: () => ipcRenderer.invoke('presentation-hide'),
  selectFiles: (o) => ipcRenderer.invoke('select-files', o),
  getFileInfo: (p) => ipcRenderer.invoke('get-file-info', p),
  readFileUrl: (p) => ipcRenderer.invoke('read-file-url', p),
  setLogo: () => ipcRenderer.invoke('set-logo'),
  getLogo: () => ipcRenderer.invoke('get-logo'),
  pptOpen: (p) => ipcRenderer.invoke('ppt-open', p),
  pptNext: () => ipcRenderer.invoke('ppt-next'),
  pptPrev: () => ipcRenderer.invoke('ppt-prev'),
  pptGoto: (n) => ipcRenderer.invoke('ppt-goto', n),
  pptClose: () => ipcRenderer.invoke('ppt-close'),
  pptGetSlide: () => ipcRenderer.invoke('ppt-get-slide'),
  pptExportSlides: (p) => ipcRenderer.invoke('ppt-export-slides', p),
  pptShowOverlay: () => ipcRenderer.invoke('ppt-show-overlay'),
  pptHideOverlay: () => ipcRenderer.invoke('ppt-hide-overlay'),
  loadBible: (v) => ipcRenderer.invoke('load-bible', v),
  getBibleVersions: () => ipcRenderer.invoke('get-bible-versions'),
  importBible: () => ipcRenderer.invoke('import-bible'),
  loadMediaLibrary: () => ipcRenderer.invoke('load-media-library'),
  saveMediaLibrary: (d) => ipcRenderer.invoke('save-media-library', d),
  onDisplayContent: (cb) => ipcRenderer.on('display-content', (e, d) => cb(d)),
  onVideoCommand: (cb) => ipcRenderer.on('video-command', (e, d) => cb(d)),
});
